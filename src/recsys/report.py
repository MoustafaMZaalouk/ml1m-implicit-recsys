"""Regenerate figures and the README results block from results/results.json only.

    python -m recsys.report            # rewrites results/*.png and the README block
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "results" / "results.json"
README = ROOT / "README.md"
BEGIN, END = "<!-- RESULTS:BEGIN (generated by `python -m recsys.report`, do not edit) -->", "<!-- RESULTS:END -->"
ORDER = ["random", "popularity", "item_knn_cosine", "als", "two_tower"]
LABEL = {"random": "Random", "popularity": "Popularity", "item_knn_cosine": "Item-KNN (cosine)",
         "als": "ALS (implicit)", "two_tower": "Two-tower MLP"}


def pm(a):
    return f"{a['mean']:.4f}" if a["std"] == 0 and False else f"{a['mean']:.4f} ± {a['std']:.4f}"


def render(r: dict) -> str:
    d, F = r["dataset"], r["final"]
    L = []
    L.append("### Dataset and split (all counts regenerated from the run)\n")
    L.append(f"- {d['n_users']:,} users, {d['n_items']:,} items, {d['n_interactions']:,} interactions "
             f"(density {d['density']:.3%}). Every rating is treated as an implicit positive.")
    L.append(f"- Train {d['n_train']:,} / validation {d['n_val']:,} (1 per user) / test {d['n_test']:,} (1 per user).")
    L.append(f"- Test items never seen in train or validation: {d['test_items_never_seen_in_train_or_val']} "
             "(counted as misses, never dropped).")
    L.append(f"- Dataset SHA-256 pin: `{d['sha256']}`.\n")
    L.append("### Test results, full-catalog ranking\n")
    L.append("Mean ± std over seeds (3 seeds for ALS and two-tower, 1 run for the deterministic models). "
             "History items are excluded from the ranking; the full catalog is ranked.\n")
    L.append("| Model | Recall@10 | Recall@20 | NDCG@10 | Coverage@10 | Coverage@20 |")
    L.append("|---|---|---|---|---|---|")
    for n in ORDER:
        a = F[n]["aggregate_over_seeds"]
        row = " | ".join(pm(a[k]) if F[n]["n_seeds"] > 1 else f"{a[k]['mean']:.4f}"
                         for k in ("recall@10", "recall@20", "ndcg@10", "coverage@10", "coverage@20"))
        L.append(f"| {LABEL[n]} | {row} |")
    L.append("\n95% bootstrap CIs over users (seed 0 run; this captures user sampling noise, not seed noise):\n")
    L.append("| Model | Recall@10 | Recall@20 | NDCG@10 |")
    L.append("|---|---|---|---|")
    for n in ORDER:
        b = F[n]["runs"][0]["bootstrap95_seed0"]
        L.append(f"| {LABEL[n]} | " + " | ".join(f"[{b[k][0]:.4f}, {b[k][1]:.4f}]" for k in ("recall@10", "recall@20", "ndcg@10")) + " |")
    L.append("\nPaired bootstrap of per-user NDCG@10 differences (seed 0, 95% CI of the mean difference):\n")
    L.append("| Comparison | Mean diff | 95% CI | CI excludes 0 |")
    L.append("|---|---|---|---|")
    for k, v in r["paired_ndcg@10_seed0"].items():
        b, a = k.split("_minus_")
        lo, hi = v["ci95"]
        L.append(f"| {LABEL[b]} − {LABEL[a]} | {v['mean_diff_ndcg@10']:+.4f} | [{lo:+.4f}, {hi:+.4f}] | {'yes' if lo > 0 or hi < 0 else 'no'} |")
    L.append("\n### Popularity-bias analysis (seed 0)\n")
    bk = r["final_buckets"]
    L.append(f"Items are bucketed by train+validation popularity: head = top 10% of the catalog ({bk['head_items']} items), "
             f"mid = next 40% ({bk['mid_items']}), tail = bottom 50% ({bk['tail_items']}).\n")
    L.append("| Model | Head share of top-10 slots | Mid | Tail | Mean popularity percentile of recs (test items: "
             f"{F['popularity']['runs'][0]['popularity_bias']['mean_popularity_percentile_of_test_items']:.3f}) | Exposure Gini@10 |")
    L.append("|---|---|---|---|---|---|")
    for n in ORDER:
        p = F[n]["runs"][0]["popularity_bias"]
        L.append(f"| {LABEL[n]} | {p['head_share_of_top10_slots']:.3f} | {p['mid_share_of_top10_slots']:.3f} | "
                 f"{p['tail_share_of_top10_slots']:.3f} | {p['mean_popularity_percentile_of_recs']:.3f} | {p['exposure_gini@10']:.3f} |")
    hs = F["popularity"]["runs"][0]["popularity_bias"]["head_share_of_test_items"]
    L.append(f"\nRecall@10 split by the popularity bucket of the held-out item (head items are {hs:.1%} of test targets; "
             "a lower percentile means more popular, 0 = most popular item):\n")
    L.append("| Model | Head targets | Mid targets | Tail targets |")
    L.append("|---|---|---|---|")
    for n in ORDER:
        rb = F[n]["runs"][0]["popularity_bias"]["recall@10_by_test_item_bucket"]
        cell = lambda b: f"{rb[b]['recall@10']:.4f} (n={rb[b]['n_users']})" if rb[b]["recall@10"] is not None else "n/a"
        L.append(f"| {LABEL[n]} | {cell('head')} | {cell('mid')} | {cell('tail')} |")
    L.append("\n### Per-user distribution of the held-out item's rank (seed 0)\n")
    L.append("Each user has one held-out item, so per-user Recall and NDCG are all-or-nothing at a given cutoff; "
             "the distribution that carries information is the rank itself.\n")
    labels = F["popularity"]["runs"][0]["per_user"]["rank_histogram"]["labels"]
    L.append("| Model | Median rank | 25th pct | 75th pct | Share with NDCG@10 = 0 | " + " | ".join(labels) + " |")
    L.append("|---|---|---|---|---|" + "---|" * len(labels))
    for n in ORDER:
        u = F[n]["runs"][0]["per_user"]
        pc = u["rank_percentiles"]
        tot = sum(u["rank_histogram"]["counts"])
        L.append(f"| {LABEL[n]} | {pc['50']:.0f} | {pc['25']:.0f} | {pc['75']:.0f} | {u['share_ndcg@10_zero']:.3f} | "
                 + " | ".join(f"{c / tot:.3f}" for c in u["rank_histogram"]["counts"]) + " |")
    L.append("\n(Columns after the first five are the share of users whose held-out item lands in that rank range.)\n")
    L.append("### Selected hyperparameters (chosen on validation NDCG@10, seed 0)\n")
    t = r["tuning"]
    L.append(f"- Item-KNN: `{ {k: v for k, v in t['item_knn_cosine']['best'].items() if k != 'val_ndcg@10'} }` "
             f"({len(t['item_knn_cosine']['grid'])} configs tried)")
    L.append(f"- ALS: `{ {k: v for k, v in t['als']['best'].items() if k != 'val_ndcg@10'} }` ({len(t['als']['grid'])} configs tried)")
    L.append(f"- Two-tower: `{ {k: v for k, v in t['two_tower']['best'].items() if k != 'val_ndcg@10'} }` "
             f"({len(t['two_tower']['grid'])} configs tried, max {t['two_tower']['epochs_max']} epochs, best epoch by validation reused for the final fit)")
    L.append("\n### Compute (CPU only)\n")
    e, ts = r["env"], r["timing_seconds"]
    L.append(f"- {e['cpu_count']} CPU core(s), PyTorch {e['torch']} on CPU with {e['torch_threads']} thread, "
             f"Python {e['python']}, numpy {e['numpy']}, scipy {e['scipy']}, pandas {e['pandas']}.")
    fin = sum(run["fit_and_eval_seconds"] for n in ORDER for run in F[n]["runs"])
    tune_total = ts["tune_item_knn"] + ts["tune_als"] + ts["tune_two_tower"]
    L.append(f"- Summed single-core compute for the whole pipeline: about {(tune_total + fin) / 60:.0f} minutes "
             f"(tuning {tune_total / 60:.0f} min: KNN {ts['tune_item_knn'] / 60:.1f}, ALS {ts['tune_als'] / 60:.1f}, two-tower {ts['tune_two_tower'] / 60:.1f}; "
             f"final fits and evaluation {fin / 60:.0f} min). The run was resumed from a cache after sandbox restarts, so these are per-step sums, not one continuous wall-clock.")
    L.append("- No GPU, no paid compute.\n")
    L.append("![metrics](results/metrics.png)\n\n![bias](results/popularity_bias.png)\n\n![ranks](results/rank_distribution.png)")
    return "\n".join(L)


def figures(r: dict):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np
    F = r["final"]
    names = [LABEL[n] for n in ORDER]
    fig, ax = plt.subplots(figsize=(7, 3.6))
    w = 0.25
    for j, (k, c) in enumerate((("recall@10", "#4c78a8"), ("recall@20", "#72b7b2"), ("ndcg@10", "#f58518"))):
        m = [F[n]["aggregate_over_seeds"][k]["mean"] for n in ORDER]
        s = [F[n]["aggregate_over_seeds"][k]["std"] for n in ORDER]
        ax.bar(np.arange(len(ORDER)) + (j - 1) * w, m, w, yerr=s, label=k, color=c, capsize=2)
    ax.set_xticks(range(len(ORDER))); ax.set_xticklabels(names, rotation=15); ax.legend()
    ax.set_title("Test metrics, full-catalog ranking (error bars: std over seeds)")
    fig.tight_layout(); fig.savefig(ROOT / "results" / "metrics.png", dpi=120); plt.close(fig)

    fig, axs = plt.subplots(1, 2, figsize=(10, 3.6))
    bot = np.zeros(len(ORDER))
    for key, c in (("head_share_of_top10_slots", "#e45756"), ("mid_share_of_top10_slots", "#f2cf5b"), ("tail_share_of_top10_slots", "#54a24b")):
        v = np.array([F[n]["runs"][0]["popularity_bias"][key] for n in ORDER])
        axs[0].bar(names, v, bottom=bot, color=c, label=key.split("_")[0]); bot += v
    axs[0].set_title("Share of top-10 slots by item popularity bucket"); axs[0].set_ylim(0, 1.15); axs[0].legend(loc="upper center", ncol=3, fontsize=8); axs[0].tick_params(axis="x", rotation=20)
    for j, (b, c) in enumerate((("head", "#e45756"), ("mid", "#f2cf5b"), ("tail", "#54a24b"))):
        v = [F[n]["runs"][0]["popularity_bias"]["recall@10_by_test_item_bucket"][b]["recall@10"] for n in ORDER]
        axs[1].bar(np.arange(len(ORDER)) + (j - 1) * 0.27, v, 0.27, color=c, label=b)
    axs[1].set_xticks(range(len(ORDER))); axs[1].set_xticklabels(names, rotation=20); axs[1].legend()
    axs[1].set_title("Recall@10 by popularity of the held-out item")
    fig.tight_layout(); fig.savefig(ROOT / "results" / "popularity_bias.png", dpi=120); plt.close(fig)

    labels = F["popularity"]["runs"][0]["per_user"]["rank_histogram"]["labels"]
    fig, ax = plt.subplots(figsize=(8, 3.6))
    for j, n in enumerate(ORDER):
        c = np.array(F[n]["runs"][0]["per_user"]["rank_histogram"]["counts"], float)
        ax.bar(np.arange(len(labels)) + (j - 2) * 0.16, c / c.sum(), 0.16, label=LABEL[n])
    ax.set_xticks(range(len(labels))); ax.set_xticklabels(labels); ax.legend(fontsize=7)
    ax.set_title("Share of users by rank of held-out item"); fig.tight_layout()
    fig.savefig(ROOT / "results" / "rank_distribution.png", dpi=120); plt.close(fig)


def inject(text: str, block: str) -> str:
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    return pat.sub(lambda m: f"{BEGIN}\n{block}\n{END}", text)


def main():
    r = json.loads(RES.read_text())
    figures(r)
    README.write_text(inject(README.read_text(), render(r)))
    print("README results block regenerated")


if __name__ == "__main__":
    main()
